-- Executar apenas APOS a Etapa 1 e a Etapa 2, com o banco CESAR selecionado.
-- Pode ser executado novamente: nao remove nem altera cadastros existentes.
-- Sem vinculacao com ARMAMENTO, ATIRADOR, CAUTELA ou sistemas biometricos.
USE CESAR;

CREATE TABLE IF NOT EXISTS PESSOA (
    ID_PESSOA INT UNSIGNED NOT NULL AUTO_INCREMENT,
    NOME VARCHAR(150) NOT NULL,
    IDENTIFICADOR VARCHAR(40) NOT NULL,
    SETOR VARCHAR(100) NOT NULL DEFAULT '',
    OBSERVACOES VARCHAR(500) NOT NULL DEFAULT '',
    FOTO_ARQUIVO VARCHAR(100) NULL,
    ATIVO TINYINT(1) NOT NULL DEFAULT 1,
    CADASTRADO_POR INT NOT NULL,
    CRIADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ATUALIZADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_PESSOA),
    UNIQUE KEY UK_PESSOA_IDENTIFICADOR (IDENTIFICADOR),
    KEY IDX_PESSOA_NOME (NOME),
    KEY IDX_PESSOA_SETOR (SETOR),
    KEY IDX_PESSOA_ATIVO (ATIVO),
    CONSTRAINT FK_PESSOA_CADASTRADO_POR
        FOREIGN KEY (CADASTRADO_POR) REFERENCES USUARIO(ID_USUARIO)
        ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

