CREATE DATABASE IF NOT EXISTS CESAR
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;
USE CESAR;

-- Tabela de Armamentos
CREATE TABLE ARMAMENTO (
    ID_ARMAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    SERIAL VARCHAR(5) NOT NULL UNIQUE,
    CONDICAO VARCHAR(150),
    DISPONIBILIDADE BOOLEAN NOT NULL DEFAULT 1
);

-- Tabela de Usuários (Auxiliares e Administradores)
CREATE TABLE USUARIO (
    ID_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(250) NOT NULL,
    ENTRADA VARCHAR(150) NOT NULL UNIQUE, -- RA ou Login
    SENHA VARCHAR(255) NOT NULL,
    CARGO ENUM('AUXILIAR', 'ADMINISTRADOR') NOT NULL
);

-- Tabela de Atiradores
CREATE TABLE ATIRADOR (
    ID_ATIRADOR INT AUTO_INCREMENT PRIMARY KEY,
    RA VARCHAR(15) NOT NULL UNIQUE,
    NOME VARCHAR(250),
    NOME_GUERRA VARCHAR(50),
    NUMERO VARCHAR(2),
    FOTO VARCHAR(255), -- caminho do arquivo enviado
    ID_DIGITAL INT UNIQUE, -- ID retornado pelo sensor biométrico no ESP32
    CODIGO_ACESSO VARCHAR(20) UNIQUE, -- para atirador sem digital
    ID_ARMAMENTO INT UNIQUE, -- 1 armamento para 1 atirador
    ID_USUARIO INT, -- Usuário que cadastrou o atirador
    FOREIGN KEY (ID_ARMAMENTO) REFERENCES ARMAMENTO(ID_ARMAMENTO),
    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

-- Tabela de Cautela (Registro de Empréstimo/Devolução)
CREATE TABLE CAUTELA (
    ID_CAUTELA INT AUTO_INCREMENT PRIMARY KEY,
    DIA DATE DEFAULT (CURRENT_DATE),
    HORA_I TIME, -- Hora que pegou a arma
    HORA_F TIME, -- Hora que devolveu a arma
    MISSAO VARCHAR(150),
    ACESSORIOS VARCHAR(255),
    COM_ALTERACAO BOOLEAN NOT NULL DEFAULT 0,
    DESCRICAO_DEVOLUCAO VARCHAR(255),
    MOTIVO_SEM_BIOMETRIA VARCHAR(255),
    ID_USUARIO INT NOT NULL, -- Auxiliar que estava na reserva de armamento
    ID_ATIRADOR INT NOT NULL, -- Atirador que pegou a arma
    ID_ARMAMENTO INT NOT NULL, -- Armamento retirado
    ID_ADMIN_AUTORIZOU INT NULL, -- Administrador que autorizou devolução sem biometria
    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    FOREIGN KEY (ID_ATIRADOR) REFERENCES ATIRADOR(ID_ATIRADOR),
    FOREIGN KEY (ID_ARMAMENTO) REFERENCES ARMAMENTO(ID_ARMAMENTO),
    FOREIGN KEY (ID_ADMIN_AUTORIZOU) REFERENCES USUARIO(ID_USUARIO)
);