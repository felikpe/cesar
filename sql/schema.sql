CREATE DATABASE IF NOT EXISTS CESAR
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;
USE CESAR;

CREATE TABLE ARMAMENTO (
    ID_ARMAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    SERIAL VARCHAR(5) NOT NULL UNIQUE,
    CONDICAO VARCHAR(150),
    MODELO ENUM('MOSQUEFAL','PRESSAO') NOT NULL,
    DISPONIBILIDADE BOOLEAN NOT NULL DEFAULT 1 -- 1 DISPONÍVEL/ 2 CAUTELADA
);

-- Tabela de Usuários (Auxiliares e Administradores)
CREATE TABLE USUARIO (
    ID_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(250) NOT NULL,
    ENTRADA VARCHAR(150) NOT NULL UNIQUE, -- Login de preferência do usuário
    SENHA VARCHAR(255) NOT NULL,
    CARGO ENUM('ARMEIRO', 'ADMINISTRADOR') NOT NULL,
    CODIGO_ACESSO VARCHAR(20) UNIQUE NULL, -- caso necessário realizar empréstimo a um atirador sem digital
    ATIVO TINYINT(1) NOT NULL DEFAULT 1 -- Deixar o armeiro inativo após o final do ano de instrução
);

-- Tabela de Atiradores
CREATE TABLE ATIRADOR (
    ID_ATIRADOR INT AUTO_INCREMENT PRIMARY KEY,
    RA VARCHAR(12) NOT NULL UNIQUE,
    NOME VARCHAR(250), -- Nome completo
    NOME_GUERRA VARCHAR(50), 
    NUMERO VARCHAR(2), -- Número baseado na antiguidade
    FOTO VARCHAR(255), -- Caminho do arquivo enviado
    ID_DIGITAL INT UNIQUE, -- ID retornado pelo sensor biométrico no ESP32
    ATIVO TINYINT(1) NOT NULL DEFAULT 1, -- Deixar o atirador inativo após o final do ano de instrução

    ID_ARMAMENTO INT UNIQUE, -- Armamento principal do atirador
    ID_USUARIO INT UNIQUE NULL, -- Para quando o atirador for armeiro
    -- CHAVES ESTRANGEIRAS
    CONSTRAINT FK_ATIRADOR_ARMAMENTO FOREIGN KEY (ID_ARMAMENTO) 
    REFERENCES ARMAMENTO(ID_ARMAMENTO),
    CONSTRAINT FK_ATIRADOR_USUARIO 
    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO) ON DELETE SET NULL
);

    -- Tabela de Cautela
CREATE TABLE CAUTELA (
    ID_CAUTELA INT AUTO_INCREMENT PRIMARY KEY,
    DIA DATE DEFAULT (CURRENT_DATE) NOT NULL,
    HORA_I TIME NOT NULL, -- Hora que pegou a arma
    HORA_F TIME NOT NULL, -- Hora que devolveu a arma
    MISSAO VARCHAR(150), -- Motivo do empréstimo
    ACESSORIOS VARCHAR(255) NULL,
    COM_ALTERACAO BOOLEAN NOT NULL DEFAULT 0,
    DESCRICAO_DEVOLUCAO VARCHAR(255) NULL,
    MOTIVO_SEM_BIOMETRIA VARCHAR(255) NULL,
    ID_USUARIO INT NOT NULL, -- Armeiro que estava na autorizou a cautela
    ID_ATIRADOR INT NOT NULL, -- Atirador que pegou a arma
    ID_ARMAMENTO INT NOT NULL, -- Armamento retirado
   -- Chaves Estrangeiras
    CONSTRAINT FK_CAUTELA_USUARIO 
    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_CAUTELA_ATIRADOR
    FOREIGN KEY (ID_ATIRADOR) REFERENCES ATIRADOR(ID_ATIRADOR),
    CONSTRAINT FK_CAUTELA_ARMAMENTO
    FOREIGN KEY (ID_ARMAMENTO) REFERENCES ARMAMENTO(ID_ARMAMENTO)
);

    -- Auditoria
CREATE TABLE LOG_SISTEMA (
    ID_LOG BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ID_USUARIO INT NULL,
    ACAO VARCHAR(100) NOT NULL,
    DESCRICAO TEXT NULL,
    IP_ORIGEM VARCHAR(45) NULL,
    CRIADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- Chave Estrangeira
    CONSTRAINT FK_LOG_USUARIO 
    FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO) ON DELETE SET NULL,
    INDEX IDX_LOG_DATA (CRIADO_EM)
) ENGINE=InnoDB;
