    RESERVA_USUARIO INT NULL,
    RESERVA_ATIRADOR INT NULL,
    RESERVA_DIGITAL INT NULL,
    RESERVA_EXPIRA_EM DATETIME NULL,
    RESERVA_CONCLUIDA BOOLEAN NOT NULL DEFAULT 0
) ENGINE=InnoDB;

