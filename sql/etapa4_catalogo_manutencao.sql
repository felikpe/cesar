USE CESAR;

ALTER TABLE ARMAMENTO
  MODIFY COLUMN SERIAL VARCHAR(100) NOT NULL,
  ADD COLUMN MODELO VARCHAR(140) NOT NULL DEFAULT '',
  ADD COLUMN FABRICANTE VARCHAR(120) NOT NULL DEFAULT '',
  ADD COLUMN DESCRICAO_CATALOGO TEXT NULL,
  ADD COLUMN FOTO_ARQUIVO VARCHAR(100) NULL,
  ADD COLUMN ESTADO_DOCUMENTAL ENUM('SEM_REGISTRO','EM_ANALISE','EM_MANUTENCAO','MANUTENCAO_CONCLUIDA') NOT NULL DEFAULT 'SEM_REGISTRO',
  ADD COLUMN CRIADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN ATUALIZADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP;

CREATE TABLE IF NOT EXISTS HISTORICO_CATALOGO (
    ID_HISTORICO BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ID_ARMAMENTO INT NOT NULL,
    ID_USUARIO INT NULL,
    TIPO_EVENTO ENUM('OBSERVACAO','DEFEITO_RELATADO','ENVIADO_MANUTENCAO','RETORNOU_MANUTENCAO') NOT NULL,
    DESCRICAO TEXT NOT NULL,
    CRIADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_HISTORICO_ARMAMENTO FOREIGN KEY (ID_ARMAMENTO)
        REFERENCES ARMAMENTO(ID_ARMAMENTO) ON DELETE RESTRICT,
    CONSTRAINT FK_HISTORICO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIO(ID_USUARIO) ON DELETE SET NULL,
    INDEX IDX_HISTORICO_ITEM_DATA (ID_ARMAMENTO, CRIADO_EM)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SELECT 'Etapa 4 instalada: catalogo e historico documental' AS RESULTADO;
