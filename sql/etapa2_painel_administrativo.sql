USE CESAR;

ALTER TABLE USUARIO
    ADD COLUMN ATIVO TINYINT(1) NOT NULL DEFAULT 1,
    ADD COLUMN PROTEGIDO TINYINT(1) NOT NULL DEFAULT 0,
    ADD COLUMN CRIADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Evita desativacao pelo painel dos dois administradores do seed inicial.
UPDATE USUARIO
SET ATIVO = 1, PROTEGIDO = 1
WHERE ENTRADA IN ('armaria@adm1', 'armaria@adm2')
  AND CARGO = 'ADMINISTRADOR';

CREATE INDEX IDX_USUARIO_CARGO_ATIVO ON USUARIO (CARGO, ATIVO);

SELECT ID_USUARIO, NOME, ENTRADA, CARGO, ATIVO, PROTEGIDO
FROM USUARIO
ORDER BY ID_USUARIO;
