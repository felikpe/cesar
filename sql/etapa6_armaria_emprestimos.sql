-- C.E.S.A.R. - ETAPA 6: armaria minimalista e movimentação de armamentos.
-- Execute APÓS as etapas anteriores. Faça backup do banco CESAR antes.
USE CESAR;

-- Remove tabelas de TI criadas em uma etapa descartada (se existirem).
DROP TABLE IF EXISTS EMPRESTIMO_TI;
DROP TABLE IF EXISTS EQUIPAMENTO_TI;

ALTER TABLE ARMAMENTO
  ADD COLUMN IF NOT EXISTS STATUS_ARMA ENUM('DISPONIVEL','EMPRESTADA','MANUTENCAO','INATIVA') NOT NULL DEFAULT 'DISPONIVEL' AFTER DISPONIBILIDADE;

UPDATE ARMAMENTO
SET STATUS_ARMA = CASE
    WHEN ESTADO_DOCUMENTAL = 'EM_MANUTENCAO' THEN 'MANUTENCAO'
    WHEN DISPONIBILIDADE = 1 THEN 'DISPONIVEL'
    ELSE 'INATIVA'
END
WHERE STATUS_ARMA IS NULL OR STATUS_ARMA = '' OR STATUS_ARMA = 'DISPONIVEL';

CREATE TABLE IF NOT EXISTS EMPRESTIMO_ARMAMENTO (
    ID_EMPRESTIMO_ARMAMENTO BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ID_ARMAMENTO INT NOT NULL,
    ID_PESSOA INT UNSIGNED NOT NULL,
    ID_USUARIO_RESPONSAVEL INT NOT NULL,
    ID_USUARIO_DEVOLUCAO INT NULL,
    DATA_EMPRESTIMO DATETIME NOT NULL,
    DATA_PREVISTA_DEVOLUCAO DATETIME NOT NULL,
    DATA_DEVOLUCAO DATETIME NULL,
    OBSERVACAO VARCHAR(500) NOT NULL DEFAULT '',
    JUSTIFICATIVA_ALTERACAO VARCHAR(500) NULL,
    OBSERVACAO_DEVOLUCAO VARCHAR(500) NULL,
    CRIADO_EM DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_EMPRESTIMO_ARMA FOREIGN KEY (ID_ARMAMENTO) REFERENCES ARMAMENTO(ID_ARMAMENTO) ON DELETE RESTRICT,
    CONSTRAINT FK_EMPRESTIMO_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES PESSOA(ID_PESSOA) ON DELETE RESTRICT,
    CONSTRAINT FK_EMPRESTIMO_USUARIO FOREIGN KEY (ID_USUARIO_RESPONSAVEL) REFERENCES USUARIO(ID_USUARIO) ON DELETE RESTRICT,
    CONSTRAINT FK_EMPRESTIMO_USUARIO_DEV FOREIGN KEY (ID_USUARIO_DEVOLUCAO) REFERENCES USUARIO(ID_USUARIO) ON DELETE RESTRICT,
    INDEX IDX_EMPRESTIMO_ARMA_ABERTO (ID_ARMAMENTO, DATA_DEVOLUCAO),
    INDEX IDX_EMPRESTIMO_DEVOLUCAO (DATA_DEVOLUCAO, DATA_PREVISTA_DEVOLUCAO),
    INDEX IDX_EMPRESTIMO_PESSOA (ID_PESSOA)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SELECT 'Etapa 6 instalada: armaria minimalista e empréstimos de armas.' AS RESULTADO;
